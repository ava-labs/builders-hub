describe('decodeMonitorLog on real logs', () => {
  it('has a real log and a declaration for every def', () => {
    expect(Object.keys(FIXTURES).sort()).toEqual(keys(MONITOR_EVENTS).sort());
    for (const d of MONITOR_EVENTS) expect(declarationOf(d.key), d.key).toBeDefined();
  });

  it.each(MONITOR_EVENTS.map((d) => [d.key, d] as const))('%s: its fields equal viem decodeEventLog', (key, d) => {
    const log = FIXTURES[key];
    const abi = parseAbiItem(declarationOf(key)) as AbiEvent;
    expect(abi.name).toBe(d.event);
    expect(toEventSignature(abi)).toBe(d.signature);
    expect(toEventSelector(abi)).toBe(d.topic0);
    expect(fitsMonitorLog(d, log)).toBe(true);
    const { args } = decodeEventLog({ abi: [abi], topics: log.topics as [`0x${string}`], data: log.data as `0x${string}`, strict: true });
    const values = args as Record<string, unknown>;
    const mine = decodeMonitorLog(d, log);
    const indexed = abi.inputs.filter((i) => 'indexed' in i && i.indexed);
    const plain = abi.inputs.filter((i) => !('indexed' in i && i.indexed));
    const read = new Set<string>();
    for (const f of d.fields) {
      // topic k is the k-th indexed input; data word k the k-th other one
      const input = f.from === 'topic' ? indexed[f.index - 1] : plain[f.index];
      expect(input, `${key} ${f.name}`).toBeDefined();
      const half = f.type === 'uint128lo' ? 'X' : f.type === 'uint128hi' ? 'Y' : '';
      expect(f.name, key).toBe(`${input.name}${half}`);
      expect(mine[f.name], `${key} ${f.name}`).toEqual(expected(values[input.name!], f.type));
      read.add(input.name!);
    }
    // every input but a dynamic one is a field
    for (const i of abi.inputs) if (i.type !== 'bytes' && i.type !== 'string') expect(read.has(i.name!), `${key} ${i.name}`).toBe(true);
    expect(Object.keys(mine)).toEqual(d.fields.map((f) => f.name));
  });

  it("takes each log from one of the def's contracts, or a pool the def's pool check keeps", () => {
    for (const d of MONITOR_EVENTS) {
      const log = FIXTURES[d.key];
      if (d.addresses) expect(d.addresses, d.key).toContain(log.address);
      if (!d.poolCheck) continue;
      const pool = log.pool!;
      if ('getter' in d.poolCheck) {
        expect([pool.call, pool.to], d.key).toEqual([d.poolCheck.getter, log.address]);
        expect(d.factories, d.key).toContain(`0x${pool.result.slice(-40)}`);
      } else {
        expect([pool.call, pool.arg], d.key).toEqual([d.poolCheck.onFactory, log.address]);
        expect(d.factories, d.key).toContain(pool.to);
        expect(BigInt(pool.result), d.key).toBe(1n);
      }
    }
  });

  it('reads LB amounts as X low and Y high, and univ4 amounts signed', () => {
    const lb = MONITOR_EVENTS.find((d) => d.key === 'trader-joe/lb-swap')!;
    const packed = { topics: FIXTURES['trader-joe/lb-swap'].topics, data: `0x${'0'.repeat(64)}${'00000000000000000000000000000002'}${'00000000000000000000000000000001'}${'0'.repeat(64 * 4)}` };
    expect(decodeMonitorLog(lb, packed)).toMatchObject({ amountsInX: 1n, amountsInY: 2n });
    const v4 = MONITOR_EVENTS.find((d) => d.key === 'uniswap/univ4-swap')!;
    const negative = { topics: FIXTURES['uniswap/univ4-swap'].topics, data: `0x${'f'.repeat(64)}${'0'.repeat(63)}1${'0'.repeat(64 * 4)}` };
    expect(decodeMonitorLog(v4, negative)).toMatchObject({ amount0: -1n, amount1: 1n });
  });

  it('tells apart a log of the same topic0 and another shape', () => {
    const erc20 = MONITOR_EVENTS.find((d) => d.key === 'erc-20/transfer')!;
    // an ERC-721 Transfer: the token id in topic3, no data
    const nft = { address: '0xb74b1f14d2754acfcbbe1a221023a5cf50ab8acd', topics: [...FIXTURES['erc-20/transfer'].topics, `0x${'0'.repeat(60)}26a6`], data: '0x' };
    expect(fitsMonitorLog(erc20, nft)).toBe(false);
    expect(() => decodeMonitorLog(erc20, nft)).toThrow(/no data 0/);
    // a univ2 Mint has Benqi's Mint topic0 with an indexed sender
    const benqi = MONITOR_EVENTS.find((d) => d.key === 'benqi/supply')!;
    const pairMint = { topics: [benqi.topic0, `0x${'0'.repeat(24)}${'1'.repeat(40)}`], data: `0x${'0'.repeat(128)}` };
    expect(fitsMonitorLog(benqi, pairMint)).toBe(false);
    // a Benqi event from a contract that is no market
    expect(fitsMonitorLog(benqi, { ...FIXTURES['benqi/supply'], address: '0x0000000000000000000000000000000000000001' })).toBe(false);
  });
});

