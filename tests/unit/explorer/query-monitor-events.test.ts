const U128 = (1n << 128n) - 1n;
/** what viem's value of an input is as the def's field type reads it */
function expected(value: unknown, type: FieldDef['type']): string | bigint | boolean {
  if (type === 'address' || type === 'bytes32') return String(value).toLowerCase();
  if (type === 'bool') return value as boolean;
  if (type === 'uint128lo') return BigInt(value as string) & U128;
  if (type === 'uint128hi') return BigInt(value as string) >> 128n;
  return BigInt(value as bigint | number);
}
const isAddress = (a: string | undefined) => !!a && /^0x[0-9a-f]{40}$/.test(a);
const keys = (defs: { key: string }[]) => defs.map((d) => d.key);
const ofFamily = (family: string) => keys(MONITOR_EVENTS.filter((d) => d.family === family));

